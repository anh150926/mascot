"""Keep the portable Expo component's assets and types in sync with Ollie's build."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

from build_data import ROOT, public_contract, read, validate_runtime

DEST = ROOT / "integrations/expo"
ASSETS = {
    ROOT / "dist/ollie.riv": DEST / "assets/ollie.riv",
    ROOT / "playground/frames/neutral.png": DEST / "assets/neutral.png",
}


def typescript_contract(contract: dict) -> str:
    properties = {prop["type"]: prop for prop in contract["properties"]}
    if set(properties) != {"enum", "boolean", "trigger"} or len(contract["properties"]) != 3:
        raise ValueError("Expo component expects one enum, boolean and trigger property")
    mood = properties["enum"]
    values = "\n".join(f"  {json.dumps(value)}," for value in mood["values"])
    return (
        "// Generated by tools/package_expo.py from data/model.json.\n"
        "export const OLLIE_MOODS = [\n"
        f"{values}\n"
        "] as const;\n\n"
        "export type OllieMood = (typeof OLLIE_MOODS)[number];\n\n"
        "export const OLLIE_RIVE = {\n"
        f"  artboard: {json.dumps(contract['artboard'])},\n"
        f"  stateMachine: {json.dumps(contract['state_machine'])},\n"
        f"  viewModel: {json.dumps(contract['view_model'])},\n"
        f"  instance: {json.dumps(contract['instance'])},\n"
        "  properties: {\n"
        f"    mood: {json.dumps(mood['name'])},\n"
        f"    asleep: {json.dumps(properties['boolean']['name'])},\n"
        f"    wave: {json.dumps(properties['trigger']['name'])},\n"
        "  },\n"
        "} as const;\n"
    )


def manifest() -> str:
    entries = {
        dest.name: {
            "bytes": source.stat().st_size,
            "sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        }
        for source, dest in ASSETS.items()
    }
    return json.dumps({"schema_version": 1, "assets": entries}, indent=2) + "\n"


def main(check: bool = False) -> None:
    model = read("data/model.json")
    validate_runtime(model)
    contract = public_contract(model)
    if contract != read("dist/data/contract.json"):
        raise ValueError("dist/data/contract.json is stale; rebuild Ollie first")
    for source in ASSETS:
        if not source.is_file() or source.stat().st_size == 0:
            raise FileNotFoundError(source)

    generated = {
        DEST / "OllieContract.ts": typescript_contract(contract),
        DEST / "asset-manifest.json": manifest(),
    }
    if check:
        for source, dest in ASSETS.items():
            if not dest.is_file() or source.read_bytes() != dest.read_bytes():
                raise ValueError(f"Expo asset is out of date: {dest}")
        for path, content in generated.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                raise ValueError(f"Expo metadata is out of date: {path}")
        print("Expo package matches the Rive build and View Model contract")
        return

    (DEST / "assets").mkdir(parents=True, exist_ok=True)
    for source, dest in ASSETS.items():
        shutil.copyfile(source, dest)
    for path, content in generated.items():
        path.write_text(content, encoding="utf-8", newline="\n")
    print("Expo package ready: .riv, static fallback, typed contract")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    main(check=parser.parse_args().check)
